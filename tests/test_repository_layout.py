"""Verify relocatable source and distribution path contracts without downloads."""
from _support import ROOT
import ast
import json
import os
from pathlib import Path
from tempfile import TemporaryDirectory
import unittest
from unittest.mock import patch

import runtime_paths


class RepositoryLayoutTests(unittest.TestCase):
    def test_source_root_is_independent_of_current_directory(self):
        previous = Path.cwd()
        with TemporaryDirectory() as temporary, patch.dict(os.environ):
            os.environ.pop('DICTATELY_ROOT', None)
            os.environ.pop('TRANSCRIBR_ROOT', None)
            try:
                os.chdir(temporary)
                self.assertEqual(runtime_paths.app_root(), ROOT)
            finally:
                os.chdir(previous)

    def test_distribution_manifest_has_all_local_application_imports(self):
        manifest = json.loads((ROOT/'assets/package-files.json').read_text(encoding='utf-8'))
        self.assertEqual(len(manifest), len(set(manifest)))
        for entry in manifest:
            source = (ROOT/entry).resolve()
            self.assertTrue(source.is_relative_to(ROOT), entry)
            if entry != 'Dictately.exe':  # Generated by the native build.
                self.assertTrue(source.is_file(), entry)
            if entry.startswith('app/') and source.suffix == '.py':
                tree = ast.parse(source.read_text(encoding='utf-8'))
                for node in ast.walk(tree):
                    names = [node.module] if isinstance(node, ast.ImportFrom) else [alias.name for alias in node.names] if isinstance(node, ast.Import) else []
                    for module in names:
                        if module and (ROOT/'app'/f'{module}.py').is_file():
                            self.assertIn(f'app/{module}.py', manifest, f'{entry} imports {module}')

    def test_dependency_includes_resolve_from_their_own_directory(self):
        for source in (ROOT/'requirements').glob('*.txt'):
            for line in source.read_text(encoding='utf-8').splitlines():
                if line.startswith('-r '):
                    self.assertTrue((source.parent/line[3:]).is_file(), str(source))
